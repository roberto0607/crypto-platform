/**
 * flagOffMatchParity.test.ts: with LEVERAGE_ENABLED off, a 1v1 match's whole
 * lifecycle is byte-for-byte what it was before leverage PR 3 (match stamping,
 * ISOLATED match-end settlement, live P&L cap).
 *
 * Two matches run through the real paths: createMatch → acceptMatch (wallets
 * funded) → longs, shorts, a partial close and a resting limit → one ends by
 * completeMatch and one by forfeitMatch, both with positions still open.
 * Every row left in matches, users (ELO), wallets, ledger_entries, orders,
 * trades, positions and equity_snapshots is dumped, ids replaced by stable
 * labels and wall-clock timestamps dropped, and compared to
 * __fixtures__/flagOffMatchParity.golden.json.
 *
 * The golden file was generated by running this same file against origin/main
 * before PR 3 (WRITE_GOLDEN=1), so a diff here means flag-off match behavior
 * changed.
 */
import { describe, it, expect, beforeAll, vi } from "vitest";

vi.mock("../../notifications/notificationService", () => ({
    notifyTriggerFired: vi.fn().mockResolvedValue(undefined),
}));

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pool } from "../../db/pool";
import { config } from "../../config";
import { resetTestData, ensureMigrations } from "../../testing/resetDb";
import { createTestUser, createTestAssetAndPair, createTestWallets } from "../../testing/fixtures";
import { seedReferenceBook, clearReferenceBooks } from "../../testing/referenceBook";
import { placeOrderWithSnapshot } from "../../trading/phase6OrderService";
import { createMatch, acceptMatch, completeMatch, forfeitMatch } from "../matchService";

const GOLDEN = join(__dirname, "__fixtures__", "flagOffMatchParity.golden.json");
const UUID = /[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/g;

type Row = Record<string, unknown>;

beforeAll(async () => {
    await ensureMigrations();
});

async function scenario(): Promise<Record<string, Row[]>> {
    await resetTestData();
    clearReferenceBooks();
    const { pair, btcAsset, usdAsset } = await createTestAssetAndPair(pool);
    const pairId = pair.id;

    const labels = new Map<string, string>([[pairId, "pair"]]);
    const label = (id: unknown, prefix: string): string | null => {
        if (id === null || id === undefined) return null;
        const key = String(id);
        if (!labels.has(key)) labels.set(key, `${prefix}${[...labels.values()].filter((l) => l.startsWith(prefix)).length + 1}`);
        return labels.get(key)!;
    };

    const user = async (name: string) => {
        const u = await createTestUser(pool, { email: `${name}@test.local` });
        await createTestWallets(pool, u.id, btcAsset.id, usdAsset.id, "0.00000000", "100000.00000000");
        labels.set(u.id, name);
        return u.id;
    };
    const alice = await user("alice");
    const bob = await user("bob");
    const carol = await user("carol");
    const dave = await user("dave");

    const accepted = async (a: string, b: string, name: string) => {
        const m = await createMatch(a, b, 24, [pairId]);
        await acceptMatch(m.id, b);
        labels.set(m.id, name);
        return m.id;
    };
    const mkt = (uid: string, matchId: string, side: "BUY" | "SELL", qty: string) =>
        placeOrderWithSnapshot(uid, { pairId, side, type: "MARKET", qty }, undefined, undefined, null, matchId);
    const lim = (uid: string, matchId: string, side: "BUY" | "SELL", qty: string, px: string) =>
        placeOrderWithSnapshot(uid, { pairId, side, type: "LIMIT", qty, limitPrice: px }, undefined, undefined, null, matchId);

    seedReferenceBook(pairId, "83000", "83010");
    const m1 = await accepted(alice, bob, "m1");
    const m2 = await accepted(carol, dave, "m2");

    await mkt(alice, m1, "BUY", "0.20000000");          // long
    await mkt(bob, m1, "SELL", "0.15000000");           // short
    seedReferenceBook(pairId, "84000", "84010");
    await mkt(alice, m1, "SELL", "0.05000000");         // partial close
    await lim(bob, m1, "BUY", "0.05000000", "80000");   // rests until match end
    await mkt(carol, m2, "SELL", "0.10000000");         // short
    await mkt(dave, m2, "BUY", "0.30000000");           // long

    seedReferenceBook(pairId, "85000", "85020");
    await completeMatch(m1);                            // both still open
    seedReferenceBook(pairId, "82000", "82010");
    await forfeitMatch(m2, carol);                      // both still open

    // ── Dump, normalized ──
    const assetSym = new Map([[btcAsset.id, "BTC"], [usdAsset.id, "USD"]]);
    const walletRows = (await pool.query(
        `SELECT id, user_id, asset_id, competition_id, match_id, balance::text, reserved::text, closed_at
         FROM wallets ORDER BY created_at, ctid`)).rows;
    for (const w of walletRows) {
        labels.set(w.id, `w:${labels.get(w.user_id)}:${assetSym.get(w.asset_id)}:${w.match_id ? labels.get(w.match_id) : "free"}`);
    }
    const orders = (await pool.query(
        `SELECT id, user_id, pair_id, side, type, limit_price::text, qty::text, qty_filled::text, status,
                reserved_wallet_id, reserved_amount::text, reserved_consumed::text, competition_id, match_id,
                source, leverage::text, margin_mode, cancel_reason, created_at
         FROM orders ORDER BY created_at, ctid`)).rows
        // The match-end force-close inserts its orders in one transaction, in
        // position-row order: within a timestamp, order by user.
        .sort((a, b) => (a.created_at - b.created_at) || String(labels.get(a.user_id)).localeCompare(String(labels.get(b.user_id))))
        .map(({ created_at: _ts, ...o }) => o);
    for (const o of orders) label(o.id, "o");
    const trades = (await pool.query(
        `SELECT id, buy_order_id, sell_order_id, price::text, qty::text, quote_amount::text, fee_amount::text,
                is_system_fill, executed_at
         FROM trades ORDER BY executed_at, ctid`)).rows
        .sort((a, b) => (a.executed_at - b.executed_at)
            || String(labels.get(a.buy_order_id ?? a.sell_order_id)).localeCompare(String(labels.get(b.buy_order_id ?? b.sell_order_id)), undefined, { numeric: true }))
        .map(({ executed_at: _ts, ...t }) => t);
    for (const t of trades) label(t.id, "t");

    const L = (id: unknown) => (id === null || id === undefined ? null : labels.get(String(id)) ?? `?${String(id)}`);

    const matches = (await pool.query(
        `SELECT id, challenger_id, opponent_id, status, duration_hours, starting_capital::text,
                challenger_pnl_pct::text, opponent_pnl_pct::text,
                challenger_trades_count, opponent_trades_count,
                challenger_win_rate::text, opponent_win_rate::text,
                challenger_score::text, opponent_score::text,
                winner_id, forfeit_user_id, elo_delta, margin_mode, max_leverage::text,
                started_at IS NOT NULL AS started, completed_at IS NOT NULL AS completed
         FROM matches ORDER BY created_at, ctid`)).rows
        .map((r) => ({
            ...r, id: L(r.id), challenger_id: L(r.challenger_id), opponent_id: L(r.opponent_id),
            winner_id: L(r.winner_id), forfeit_user_id: L(r.forfeit_user_id),
        }));
    const users = (await pool.query(
        `SELECT id, elo_rating, win_count, loss_count, win_streak, loss_streak FROM users`)).rows
        .map((r) => ({ ...r, id: L(r.id) }))
        .sort((a, b) => String(a.id).localeCompare(String(b.id)));
    // One transaction's rows share created_at. Match-end settlement writes
    // them in wallet-UUID order (random), so within a transaction sort by the
    // wallet's label; ctid keeps each wallet's own insert order.
    const ledger = (await pool.query(
        `SELECT wallet_id, entry_type, amount::text, balance_after::text, reference_id, reference_type, metadata,
                created_at
         FROM ledger_entries ORDER BY created_at, ctid`)).rows
        .map((r) => ({
            ...r,
            wallet_id: L(r.wallet_id),
            reference_id: L(r.reference_id),
            metadata: JSON.parse(JSON.stringify(r.metadata).replace(UUID, (id) => L(id) ?? id)),
        }))
        .map((r, i) => ({ r, i }))
        .sort((a, b) => (a.r.created_at - b.r.created_at) || String(a.r.wallet_id).localeCompare(String(b.r.wallet_id)) || a.i - b.i)
        .map(({ r: { created_at: _ts, ...r } }) => r);
    const positions = (await pool.query(
        `SELECT user_id, competition_id, match_id, base_qty::text, avg_entry_price::text,
                realized_pnl_quote::text, fees_paid_quote::text,
                margin_mode, leverage::text, isolated_margin::text, liq_price::text, epoch, opened_at
         FROM positions`)).rows
        .map((r) => ({ ...r, user_id: L(r.user_id), competition_id: L(r.competition_id), match_id: L(r.match_id) }))
        .sort((a, b) => JSON.stringify([a.user_id, a.match_id]).localeCompare(JSON.stringify([b.user_id, b.match_id])));
    const equity = (await pool.query(
        `SELECT user_id, competition_id, match_id, equity_quote::text, cash_quote::text, holdings_quote::text,
                unrealized_pnl_quote::text, realized_pnl_quote::text, fees_paid_quote::text
         FROM equity_snapshots ORDER BY ts, ctid`)).rows
        .map((r) => ({ ...r, user_id: L(r.user_id), competition_id: L(r.competition_id), match_id: L(r.match_id) }));

    return {
        matches,
        users,
        wallets: walletRows.map((w) => ({
            id: L(w.id), balance: w.balance, reserved: w.reserved, closed: w.closed_at !== null,
        })),
        ledger,
        orders: orders.map((o) => ({
            ...o, id: L(o.id), user_id: L(o.user_id), pair_id: "pair", reserved_wallet_id: L(o.reserved_wallet_id),
            competition_id: L(o.competition_id), match_id: L(o.match_id),
        })),
        trades: trades.map((t) => ({ ...t, id: L(t.id), buy_order_id: L(t.buy_order_id), sell_order_id: L(t.sell_order_id) })),
        positions,
        equity,
    };
}

describe("LEVERAGE_ENABLED off: match lifecycle", () => {
    it("leaves exactly the rows the pre-PR-3 code left", async () => {
        expect(config.leverage.enabled).toBe(false);
        const dump = await scenario();

        if (process.env.WRITE_GOLDEN === "1") {
            writeFileSync(GOLDEN, JSON.stringify(dump, null, 2) + "\n");
            return;
        }
        const golden = JSON.parse(readFileSync(GOLDEN, "utf8"));
        expect(JSON.parse(JSON.stringify(dump))).toEqual(golden);
    });
});
