/**
 * flagOffParity.test.ts: with LEVERAGE_ENABLED off, trading is byte-for-byte
 * what it was before the ISOLATED engine path (PR 2 of the leverage plan).
 *
 * One scripted session (longs, shorts, a flip, a resting limit + cancel, user
 * and bot maker fills, the bot as taker, a competition and a match) runs
 * through the real order pipeline. Every row it leaves in wallets,
 * ledger_entries, orders, trades, positions and equity_snapshots is dumped,
 * with ids replaced by stable labels and wall-clock timestamps dropped, and
 * compared to __fixtures__/flagOffParity.golden.json.
 *
 * The golden file was generated by running this same file against origin/main
 * before the engine change (WRITE_GOLDEN=1), so a diff here means flag-off
 * behavior changed.
 */
import { describe, it, expect, beforeAll } from "vitest";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pool } from "../../db/pool";
import { config } from "../../config";
import { resetTestData, ensureMigrations } from "../../testing/resetDb";
import { createTestUser, createTestAssetAndPair, createTestWallets, fundTestMatchWallets } from "../../testing/fixtures";
import { seedReferenceBook, clearReferenceBooks } from "../../testing/referenceBook";
import { placeOrderWithSnapshot, cancelOrderWithOutbox } from "../phase6OrderService";

const GOLDEN = join(__dirname, "__fixtures__", "flagOffParity.golden.json");
const UUID = /[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/g;

type Row = Record<string, unknown>;

beforeAll(async () => {
    await ensureMigrations();
});

async function scenario(): Promise<Record<string, Row[]>> {
    await resetTestData();
    clearReferenceBooks();
    const { pair, btcAsset, usdAsset } = await createTestAssetAndPair(pool);
    const pairId = pair.id;

    const labels = new Map<string, string>();
    const label = (id: unknown, prefix: string): string | null => {
        if (id === null || id === undefined) return null;
        const key = String(id);
        if (!labels.has(key)) labels.set(key, `${prefix}${[...labels.values()].filter((l) => l.startsWith(prefix)).length + 1}`);
        return labels.get(key)!;
    };

    const user = async (name: string, usd: string, btc = "0.00000000") => {
        const u = await createTestUser(pool, { email: `${name}@test.local` });
        await createTestWallets(pool, u.id, btcAsset.id, usdAsset.id, btc, usd);
        labels.set(u.id, name);
        return u.id;
    };
    const alice = await user("alice", "100000.00000000");
    const bob = await user("bob", "50000.00000000");
    const bot = (await createTestUser(pool, { email: "mmbot@system.local" })).id;
    await createTestWallets(pool, bot, btcAsset.id, usdAsset.id, "5.00000000", "500000.00000000");
    labels.set(bot, "bot");

    const mkt = (uid: string, side: "BUY" | "SELL", qty: string, comp: string | null = null, match: string | null = null) =>
        placeOrderWithSnapshot(uid, { pairId, side, type: "MARKET", qty }, undefined, undefined, comp, match);
    const lim = (uid: string, side: "BUY" | "SELL", qty: string, px: string) =>
        placeOrderWithSnapshot(uid, { pairId, side, type: "LIMIT", qty, limitPrice: px });

    seedReferenceBook(pairId, "83000", "83010");
    await mkt(alice, "BUY", "0.10000000");                 // long, system fill at the ask
    await lim(bot, "SELL", "0.20000000", "83005");         // bot liquidity inside the touch
    await mkt(alice, "BUY", "0.05000000");                 // takes the bot (maker fee 0)
    seedReferenceBook(pairId, "84000", "84010");
    await mkt(alice, "SELL", "0.08000000");                // partial close
    await mkt(bob, "SELL", "0.10000000");                  // short
    const rest = await lim(bob, "BUY", "0.05000000", "80000"); // rests
    await cancelOrderWithOutbox(bob, rest.order.id);
    await lim(alice, "SELL", "0.04000000", "84005");       // alice rests a sell
    await mkt(bob, "BUY", "0.04000000");                   // bob covers off alice (user maker)
    seedReferenceBook(pairId, "82000", "82010");
    await mkt(bob, "BUY", "0.20000000");                   // flip short → long
    await mkt(bot, "SELL", "0.01000000");                  // the bot as taker

    const { rows: [comp] } = await pool.query<{ id: string }>(
        `INSERT INTO competitions (name, start_at, end_at) VALUES ('c', now(), now() + interval '1 day') RETURNING id`);
    labels.set(comp.id, "comp");
    for (const [asset, bal] of [[usdAsset.id, "20000"], [btcAsset.id, "0"]]) {
        await pool.query(
            `INSERT INTO wallets (user_id, asset_id, balance, reserved, competition_id) VALUES ($1, $2, $3, 0, $4)`,
            [alice, asset, bal, comp.id]);
    }
    await mkt(alice, "BUY", "0.10000000", comp.id);

    const { rows: [m] } = await pool.query<{ id: string }>(
        `INSERT INTO matches (challenger_id, opponent_id, duration_hours, starting_capital, status, started_at, ends_at)
         VALUES ($1, $2, 24, '10000', 'ACTIVE', now(), now() + interval '1 day') RETURNING id`, [alice, bob]);
    labels.set(m.id, "match");
    await fundTestMatchWallets(pool, m.id, [alice, bob], "10000");
    await mkt(bob, "SELL", "0.05000000", null, m.id);
    await mkt(bob, "BUY", "0.02000000", null, m.id);

    // ── Dump, normalized ──
    const assetSym = new Map([[btcAsset.id, "BTC"], [usdAsset.id, "USD"]]);
    const walletRows = (await pool.query(
        `SELECT id, user_id, asset_id, competition_id, match_id, balance::text, reserved::text, closed_at
         FROM wallets ORDER BY created_at, ctid`)).rows;
    for (const w of walletRows) {
        labels.set(w.id, `w:${labels.get(w.user_id)}:${assetSym.get(w.asset_id)}:${w.match_id ? "match" : w.competition_id ? "comp" : "free"}`);
    }
    const orders = (await pool.query(
        `SELECT id, user_id, pair_id, side, type, limit_price::text, qty::text, qty_filled::text, status,
                reserved_wallet_id, reserved_amount::text, reserved_consumed::text, competition_id, match_id,
                source, leverage::text
         FROM orders ORDER BY created_at, ctid`)).rows;
    for (const o of orders) label(o.id, "o");
    const trades = (await pool.query(
        `SELECT id, buy_order_id, sell_order_id, price::text, qty::text, quote_amount::text, fee_amount::text,
                is_system_fill
         FROM trades ORDER BY executed_at, ctid`)).rows;
    for (const t of trades) label(t.id, "t");

    const L = (id: unknown) => (id === null || id === undefined ? null : labels.get(String(id)) ?? `?${String(id)}`);

    const ledger = (await pool.query(
        `SELECT wallet_id, entry_type, amount::text, balance_after::text, reference_id, reference_type, metadata
         FROM ledger_entries ORDER BY created_at, ctid`)).rows
        .map((r) => ({
            ...r,
            wallet_id: L(r.wallet_id),
            reference_id: L(r.reference_id),
            metadata: JSON.parse(JSON.stringify(r.metadata).replace(UUID, (id) => L(id) ?? id)),
        }));
    const positions = (await pool.query(
        `SELECT user_id, competition_id, match_id, base_qty::text, avg_entry_price::text,
                realized_pnl_quote::text, fees_paid_quote::text,
                margin_mode, leverage::text, isolated_margin::text, liq_price::text, epoch, opened_at
         FROM positions`)).rows
        .map((r) => ({ ...r, user_id: L(r.user_id), competition_id: L(r.competition_id), match_id: L(r.match_id) }))
        .sort((a, b) => JSON.stringify([a.user_id, a.competition_id, a.match_id]).localeCompare(JSON.stringify([b.user_id, b.competition_id, b.match_id])));
    const equity = (await pool.query(
        `SELECT user_id, competition_id, match_id, equity_quote::text, cash_quote::text, holdings_quote::text,
                unrealized_pnl_quote::text, realized_pnl_quote::text, fees_paid_quote::text
         FROM equity_snapshots ORDER BY ts, ctid`)).rows
        .map((r) => ({ ...r, user_id: L(r.user_id), competition_id: L(r.competition_id), match_id: L(r.match_id) }));

    return {
        wallets: walletRows.map((w) => ({
            id: L(w.id), balance: w.balance, reserved: w.reserved, closed: w.closed_at !== null,
        })),
        ledger,
        orders: orders.map((o) => ({
            ...o, id: L(o.id), user_id: L(o.user_id), pair_id: "pair", reserved_wallet_id: L(o.reserved_wallet_id),
            competition_id: L(o.competition_id), match_id: L(o.match_id),
        })),
        trades: trades.map((t) => ({ ...t, id: L(t.id), buy_order_id: L(t.buy_order_id), sell_order_id: L(t.sell_order_id) })),
        positions,
        equity,
    };
}

describe("LEVERAGE_ENABLED off", () => {
    it("leaves exactly the rows the pre-leverage engine left", async () => {
        expect(config.leverage.enabled).toBe(false);
        const dump = await scenario();

        if (process.env.WRITE_GOLDEN === "1") {
            writeFileSync(GOLDEN, JSON.stringify(dump, null, 2) + "\n");
            return;
        }
        const golden = JSON.parse(readFileSync(GOLDEN, "utf8"));
        expect(JSON.parse(JSON.stringify(dump))).toEqual(golden);

        // The new column (migration 098) is the default on every order.
        const { rows } = await pool.query<{ margin_mode: string }>(`SELECT DISTINCT margin_mode FROM orders`);
        expect(rows).toEqual([{ margin_mode: "SPOT" }]);
    });
});
