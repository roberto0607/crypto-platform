#!/usr/bin/env node
/**
 * Copies the shared indicator math (packages/indicators/src) into each app.
 *
 * Both Docker builds use their app directory as the build context, so neither
 * can import a package outside it. Instead each app gets a committed,
 * byte-identical generated copy, and CI runs `--check` so a copy can never
 * drift from the source.
 *
 *   node scripts/sync-indicators.mjs          # regenerate the copies
 *   node scripts/sync-indicators.mjs --check  # exit 1 if any copy differs
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = "packages/indicators/src";
const TARGETS = ["apps/api/src/indicators/shared", "apps/web/src/lib/sharedIndicators"];

const header = (file) =>
  `// GENERATED by scripts/sync-indicators.mjs from ${SOURCE}/${file} — do not edit.\n` +
  `// Edit the source, then run: node scripts/sync-indicators.mjs\n`;

const listTs = (dir) =>
  existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(".ts")).sort() : [];

const sourceFiles = listTs(join(ROOT, SOURCE));
const expected = new Map(
  sourceFiles.map((f) => [f, header(f) + readFileSync(join(ROOT, SOURCE, f), "utf8")]),
);

const check = process.argv.includes("--check");
const problems = [];

for (const target of TARGETS) {
  const dir = join(ROOT, target);
  const present = listTs(dir);
  for (const f of present) {
    if (!expected.has(f)) {
      if (check) problems.push(`${target}/${f}: not in ${SOURCE}`);
      else rmSync(join(dir, f));
    }
  }
  for (const [f, content] of expected) {
    const path = join(dir, f);
    const current = existsSync(path) ? readFileSync(path, "utf8") : null;
    if (current === content) continue;
    if (check) problems.push(`${target}/${f}: ${current === null ? "missing" : "differs from source"}`);
    else {
      mkdirSync(dir, { recursive: true });
      writeFileSync(path, content);
    }
  }
}

if (check) {
  if (problems.length > 0) {
    console.error("Shared indicator copies are out of sync with packages/indicators/src:");
    for (const p of problems) console.error(`  ${p}`);
    console.error("Edit packages/indicators/src, then run: node scripts/sync-indicators.mjs");
    process.exit(1);
  }
  console.log(`shared indicators in sync (${sourceFiles.length} files × ${TARGETS.length} apps)`);
} else {
  console.log(`synced ${sourceFiles.length} files into ${TARGETS.join(", ")}`);
}
